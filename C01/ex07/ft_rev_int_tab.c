void	ft_rev_int_tab(int *tab, int size)
{
	int	i;
	int	temp;
	int	e;

	e = size - 1;
	i = 0;
	while (i < e)
	{
		temp = tab[i];
		tab[i] = tab[e];
		tab[e] = temp;
		i++;
		e--;
	}
}
